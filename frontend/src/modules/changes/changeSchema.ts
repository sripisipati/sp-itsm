export function toChangePayload(values: ChangeFormValues, version?: number): Record<string, unknown> {
  const date = (value?: string) => (value ? new Date(value).toISOString() : undefined);
  const number = (value?: string) => (value ? Number(value) : undefined);
  const text = (value?: string) => {
    const trimmed = value?.trim();
    return trimmed ? trimmed : undefined;
  };
  return {
    shortDescription: values.shortDescription.trim(),
    description: values.description.trim(),
    type: values.type,
    templateId: text(values.templateId),
    categoryId: text(values.categoryId),
    subcategoryId: text(values.subcategoryId),
    requestedById: text(values.requestedById),
    requestedForId: text(values.requestedForId),
    businessJustification: text(values.businessJustification),
    businessServiceId: text(values.businessServiceId),
    configurationItemId: text(values.configurationItemId),
    relatedIncidentId: text(values.relatedIncidentId),
    relatedProblemId: text(values.relatedProblemId),
    emergencyJustification: text(values.emergencyJustification),
    businessImpact: text(values.businessImpact),
    technicalImpact: text(values.technicalImpact),
    urgency: text(values.urgency),
    probability: text(values.probability),
    impactedUsers: number(values.impactedUsers),
    downtimeRequired: Boolean(values.downtimeRequired),
    estimatedDowntimeMinutes: number(values.estimatedDowntimeMinutes),
    riskAssessmentNarrative: text(values.riskAssessmentNarrative),
    impactAnalysis: text(values.impactAnalysis),
    affectedCiIds: values.affectedCiIds ?? [],
    affectedServiceIds: values.affectedServiceIds ?? [],
    plannedStart: date(values.plannedStart),
    plannedEnd: date(values.plannedEnd),
    actualStart: date(values.actualStart),
    actualEnd: date(values.actualEnd),
    maintenanceWindowId: text(values.maintenanceWindowId),
    assignmentGroupId: text(values.assignmentGroupId),
    implementationGroupId: text(values.implementationGroupId),
    changeOwnerId: text(values.changeOwnerId),
    implementationLeadId: text(values.implementationLeadId),
    changeCoordinatorId: text(values.changeCoordinatorId),
    assignedToId: text(values.assignedToId),
    backoutRequired: Boolean(values.backoutRequired),
    backoutPlan: text(values.backoutPlan),
    backoutTriggerConditions: text(values.backoutTriggerConditions),
    rollbackSteps: text(values.rollbackSteps),
    rollbackDurationMinutes: number(values.rollbackDurationMinutes),
    rollbackOwnerId: text(values.rollbackOwnerId),
    testPlan: text(values.testPlan),
    implementationStatus: text(values.implementationStatus),
    implementationSummary: text(values.implementationSummary),
    implementationOutcome: text(values.implementationOutcome),
    serviceImpactSummary: text(values.serviceImpactSummary),
    issuesEncountered: text(values.issuesEncountered),
    rollbackExecuted: Boolean(values.rollbackExecuted),
    resolutionDetails: text(values.resolutionDetails),
    ...(version ? { version } : {}),
  };
}
