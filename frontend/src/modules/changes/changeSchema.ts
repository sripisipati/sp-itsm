import { z } from "zod";

const wholeNumber = z.string().optional().refine((value) => !value || /^\d+$/.test(value), "Enter a whole number");

export const changeFormSchema = z.object({
  shortDescription: z.string().trim().min(3, "Short description is required"),
  description: z.string().trim().min(3, "Detailed description is required"),
  type: z.enum(["STANDARD", "NORMAL", "EMERGENCY"]),
  templateId: z.string().optional(),
  categoryId: z.string().optional(),
  subcategoryId: z.string().optional(),
  requestedById: z.string().optional(),
  requestedForId: z.string().optional(),
  businessJustification: z.string().optional(),
  businessServiceId: z.string().optional(),
  configurationItemId: z.string().optional(),
  relatedIncidentId: z.string().optional(),
  relatedProblemId: z.string().optional(),
  emergencyJustification: z.string().optional(),
  businessImpact: z.string().optional(),
  technicalImpact: z.string().optional(),
  urgency: z.string().optional(),
  probability: z.string().optional(),
  impactedUsers: wholeNumber,
  downtimeRequired: z.boolean().optional(),
  estimatedDowntimeMinutes: wholeNumber,
  riskAssessmentNarrative: z.string().optional(),
  impactAnalysis: z.string().optional(),
  affectedCiIds: z.array(z.string()).optional(),
  affectedServiceIds: z.array(z.string()).optional(),
  plannedStart: z.string().optional(),
  plannedEnd: z.string().optional(),
  actualStart: z.string().optional(),
  actualEnd: z.string().optional(),
  maintenanceWindowId: z.string().optional(),
  assignmentGroupId: z.string().optional(),
  implementationGroupId: z.string().optional(),
  changeOwnerId: z.string().optional(),
  implementationLeadId: z.string().optional(),
  changeCoordinatorId: z.string().optional(),
  assignedToId: z.string().optional(),
  backoutRequired: z.boolean().optional(),
  backoutPlan: z.string().optional(),
  backoutTriggerConditions: z.string().optional(),
  rollbackSteps: z.string().optional(),
  rollbackDurationMinutes: wholeNumber,
  rollbackOwnerId: z.string().optional(),
  testPlan: z.string().optional(),
  implementationStatus: z.string().optional(),
  implementationSummary: z.string().optional(),
  implementationOutcome: z.string().optional(),
  serviceImpactSummary: z.string().optional(),
  issuesEncountered: z.string().optional(),
  rollbackExecuted: z.boolean().optional(),
  resolutionDetails: z.string().optional(),
}).superRefine((value, ctx) => {
  if (value.type === "EMERGENCY" && !value.emergencyJustification?.trim()) {
    ctx.addIssue({ code: z.ZodIssueCode.custom, path: ["emergencyJustification"], message: "Emergency justification is required" });
  }
  if (value.type === "EMERGENCY" && !value.backoutPlan?.trim()) {
    ctx.addIssue({ code: z.ZodIssueCode.custom, path: ["backoutPlan"], message: "Emergency changes require a backout plan" });
  }
  if (value.plannedStart && value.plannedEnd && new Date(value.plannedEnd) <= new Date(value.plannedStart)) {
    ctx.addIssue({ code: z.ZodIssueCode.custom, path: ["plannedEnd"], message: "Planned end must be after planned start" });
  }
  if (value.actualStart && value.actualEnd && new Date(value.actualEnd) <= new Date(value.actualStart)) {
    ctx.addIssue({ code: z.ZodIssueCode.custom, path: ["actualEnd"], message: "Actual end must be after actual start" });
  }
});

